// swift-tools-version: 5.9
import PackageDescription

// React Native 0.88 SwiftPM autolinking evaluates this manifest through a
// symlink at <app>/ios/build/generated/autolinking/libs/ReactNativePurchasely.
// Relative React Native package paths are therefore resolved from that stable
// generated location, not directly from node_modules.
//
// CocoaPods remains supported through react-native-purchasely.podspec. This
// manifest is the self-managed SwiftPM path required because this bridge mixes
// Swift and Objective-C, which React Native's automatic SPM scaffolder cannot
// represent as a single target.

let reactNativeHeaders: [Target.Dependency] = [
    .product(name: "ReactHeaders", package: "ReactNative"),
    .product(name: "ReactNativeHeaders", package: "ReactNative"),
    .product(name: "ReactNativeDependenciesHeaders", package: "ReactNative"),
]

let purchaselySDK: Target.Dependency =
    .product(name: "Purchasely", package: "Purchasely")

let package = Package(
    name: "ReactNativePurchasely",
    platforms: [
        .iOS("15.1"),
    ],
    products: [
        .library(
            name: "ReactNativePurchasely",
            targets: [
                "ReactNativePurchaselyBridge",
                "ReactNativePurchaselyViews",
            ]
        ),
    ],
    dependencies: [
        // This is the React Native package generated by the app's SwiftPM setup.
        // The app owns the exact RN version/flavor; the library only consumes
        // the invariant header products.
        .package(name: "ReactNative", path: "../../../../xcframeworks"),
        .package(
            name: "Purchasely",
            url: "https://github.com/Purchasely/Purchasely-iOS.git",
            exact: "6.2.0"
        ),
    ],
    targets: [
        // SwiftPM does not support mixed Swift/Objective-C source targets.
        // Keep the small Swift-only transition shim separate so the ObjC bridge
        // can consume its generated Objective-C interface.
        .target(
            name: "ReactNativePurchaselyTransition",
            dependencies: [
                purchaselySDK,
            ],
            path: "ios",
            sources: [
                "PLYTransitionFactory.swift",
            ]
        ),

        // Objective-C React Native bridge + hybrid helpers.
        .target(
            name: "ReactNativePurchaselyBridge",
            dependencies: [
                "ReactNativePurchaselyTransition",
                purchaselySDK,
            ] + reactNativeHeaders,
            path: "ios",
            sources: [
                "PurchaselyRN.m",
                "PurchaselyViewManager.m",
                "Classes/Hybrid",
            ],
            publicHeadersPath: ".",
            cSettings: [
                .define("REACT_NATIVE_PURCHASELY_SWIFTPM", to: "1"),
                .headerSearchPath("Classes/Hybrid"),
            ],
            linkerSettings: [
                .linkedFramework("UIKit"),
            ]
        ),

        // The embedded presentation view is Swift and calls back into the ObjC
        // bridge. Keeping it in its own target preserves the existing source
        // layout for CocoaPods while satisfying SwiftPM's language boundary.
        .target(
            name: "ReactNativePurchaselyViews",
            dependencies: [
                "ReactNativePurchaselyBridge",
                purchaselySDK,
            ] + reactNativeHeaders,
            path: "ios",
            sources: [
                "PurchaselyView.swift",
                "PurchaselyViewManager.swift",
            ]
        ),
    ]
)
