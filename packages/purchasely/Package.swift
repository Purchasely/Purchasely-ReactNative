// swift-tools-version: 5.9
import PackageDescription

// React Native 0.88 SwiftPM autolinking evaluates this manifest through a
// symlink at <app>/ios/build/generated/autolinking/libs/ReactNativePurchasely.
// Relative React Native package paths are therefore resolved from that stable
// generated location, not directly from node_modules.
//
// CocoaPods remains supported through react-native-purchasely.podspec. This
// manifest is the self-managed SwiftPM path required because this bridge mixes
// Swift and Objective-C, which React Native's automatic SPM scaffolder cannot
// represent as a single target.

let reactNativeHeaders: [Target.Dependency] = [
    .product(name: "ReactHeaders", package: "ReactNative"),
    .product(name: "ReactNativeHeaders", package: "ReactNative"),
    .product(name: "ReactNativeDependenciesHeaders", package: "ReactNative"),
]

let purchaselySDK: Target.Dependency =
    .product(name: "Purchasely", package: "PurchaselySPM")

let bridgeDependencies: [Target.Dependency] = [
    purchaselySDK,
] + reactNativeHeaders

let viewDependencies: [Target.Dependency] = [
    "ReactNativePurchaselyBridge",
    purchaselySDK,
] + reactNativeHeaders

let viewRegistrationDependencies: [Target.Dependency] = [
    "ReactNativePurchaselyViews",
] + reactNativeHeaders

let packageDependencies: [Package.Dependency] = [
    // Generated by the consuming app's React Native SwiftPM setup.
    .package(name: "ReactNative", path: "../../../../xcframeworks"),
    // The iOS SDK binary target that CocoaPods apps also use: its url and checksum are the
    // only iOS SDK pin. The path is inside this package, so it resolves through the symlink.
    .package(path: "ios/PurchaselySPM"),
]

let packageProducts: [Product] = [
    .library(
        name: "ReactNativePurchasely",
        targets: [
            "ReactNativePurchaselyBridge",
            "ReactNativePurchaselyViews",
            "ReactNativePurchaselyViewRegistration",
        ]
    ),
]

let packageTargets: [Target] = [
    // Objective-C React Native bridge + hybrid helpers.
    .target(
        name: "ReactNativePurchaselyBridge",
        dependencies: bridgeDependencies,
        path: "ios",
        sources: [
            "PurchaselyRN.m",
            "Classes/Hybrid",
        ],
        publicHeadersPath: ".",
        cSettings: [
            .define("REACT_NATIVE_PURCHASELY_SWIFTPM", to: "1"),
            .headerSearchPath("Classes/Hybrid"),
        ],
        linkerSettings: [
            .linkedFramework("UIKit"),
        ]
    ),

    // The embedded presentation view is Swift and calls back into the ObjC
    // bridge. Keeping it in its own target preserves the existing source
    // layout for CocoaPods while satisfying SwiftPM's language boundary.
    .target(
        name: "ReactNativePurchaselyViews",
        dependencies: viewDependencies,
        path: "ios",
        sources: [
            "PurchaselyView.swift",
            "PurchaselyViewManager.swift",
            "PurchaselyRN.swift",
            "PurchaselyRN+Attributes.swift",
            "PurchaselyRN+Interceptors.swift",
            "PurchaselyRN+Lifecycle.swift",
            "PurchaselyRN+Presentations.swift",
            "PurchaselyRN+Products.swift",
            "Classes/Serialization/PLYOfferSignature+Bridge.swift",
            "Classes/Serialization/PLYPlan+Bridge.swift",
            "Classes/Serialization/PLYPresentationPlan+Bridge.swift",
            "Classes/Serialization/PLYProduct+Bridge.swift",
            "Classes/Serialization/UIColor+PLYHex.swift",
        ]
    ),

    // RCT_EXTERN_REMAP_MODULE is Objective-C while PurchaselyViewManager is
    // Swift, so the registration lives in its own ObjC target. The Swift class
    // is public under SWIFT_PACKAGE only: Release builds do not export internal
    // symbols across targets.
    .target(
        name: "ReactNativePurchaselyViewRegistration",
        dependencies: viewRegistrationDependencies,
        path: "swiftpm/ViewRegistration",
        sources: [
            "PurchaselyViewManagerRegistration.m",
        ],
        publicHeadersPath: "include"
    ),
]

let package = Package(
    name: "ReactNativePurchasely",
    // No tvOS: React Native 0.88 SwiftPM builds iOS only (react-native-tvos is a separate fork).
    platforms: [
        .iOS("15.1"),
    ],
    products: packageProducts,
    dependencies: packageDependencies,
    targets: packageTargets
)
